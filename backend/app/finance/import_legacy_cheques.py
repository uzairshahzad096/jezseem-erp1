def run(apply: bool) -> None:
    db = SessionLocal()
    try:
        db.execute(text("alter table voucher_import_staging add column if not exists cheque_date date"))
        dated = filled = kept = 0
        for code, vouchers in CHEQUES.items():
            for number, reference, on in vouchers:
                rows = db.execute(text(
                    "select v.source_voucher_id, v.reference_number from voucher_import_staging v "
                    "join customer_receipts r on r.id = v.posted_receipt_id "
                    "join business_partners p on p.id = r.customer_id "
                    "where v.voucher_number = :n and p.code = :c"), {"n": number, "c": code}).all()
                if len(rows) != 1:
                    print(f"  {code} {number}: {len(rows)} vouchers found, left alone")
                    continue
                voucher_id, existing = rows[0]
                existing = (existing or "").strip()
                if existing and reference and existing != reference:
                    print(f"  {code} {number}: export has '{existing}', screen has '{reference}'; export kept")
                    kept += 1
                if not existing and reference:
                    filled += 1
                db.execute(text(
                    "update voucher_import_staging set cheque_date = coalesce(:d, cheque_date), "
                    "reference_number = coalesce(nullif(trim(reference_number), ''), :r) where source_voucher_id = :i"),
                    {"d": datetime.strptime(on, "%m/%d/%Y").date() if on else None, "r": reference, "i": voucher_id})
                dated += 1
        db.execute(text("alter table voucher_import_staging add column if not exists wht_amount numeric(18, 2)"))
        split = 0
        for code, vouchers in WITHHELD.items():
            for number, amount in vouchers:
                split += db.execute(text(
                    "update voucher_import_staging v set wht_amount = :a from customer_receipts r, business_partners p "
                    "where r.id = v.posted_receipt_id and p.id = r.customer_id and v.voucher_number = :n "
                    "and p.code = :c and v.debit_total > :a"), {"a": amount, "n": number, "c": code}).rowcount
        print(f"Tax withheld recorded on {split} vouchers.")
        print(f"Cheque date set on {dated} vouchers; reference filled on {filled}; {kept} differed and were kept.")
        if apply:
            db.commit()
            print("Committed.")
        else:
            db.rollback()
            print("Dry run: nothing was changed.")
    finally:
        db.close()


if __name__ == "__main__":
    run(apply="--apply" in sys.argv)
