def run(apply: bool) -> None:
    db = SessionLocal()
    try:
        company = db.scalar(select(Company).order_by(Company.created_at).limit(1))
        user = db.scalar(select(User).where(User.username == settings.DEV_USER_USERNAME)) or db.scalar(
            select(User).where(User.is_superuser.is_(True)).limit(1))
        audit = AuditContext.for_user(user)
        moved = same = 0
        for code, listing in OLD_DATES.items():
            customer = db.scalar(select(BusinessPartner).where(
                BusinessPartner.company_id == company.id, BusinessPartner.code == code))
            for entry in listing.replace("\n", "").split("|"):
                number, on = entry.split()
                on = datetime.strptime(on, "%m/%d/%Y").date()
                order = db.scalar(select(SalesDocument).where(
                    SalesDocument.company_id == company.id, SalesDocument.doc_type == SALES_ORDER,
                    SalesDocument.doc_number == number, SalesDocument.customer_id == customer.id))
                journal = db.get(JournalEntry, order.journal_entry_id) if order and order.journal_entry_id else None
                if journal is None or journal.status != POSTED:
                    print(f"  {customer.name[:28]:<28} {number}: not a posted invoice of this customer, left alone")
                    continue
                if journal.journal_date == on:
                    same += 1
                    continue
                item = db.scalar(select(ARItem).where(ARItem.sales_document_id == order.id, ARItem.status == "OPEN"))
                if item is None or subledger.active_allocations(db, item.id, "to"):
                    print(f"  {customer.name[:28]:<28} {number}: has payments matched to it, left alone")
                    continue

                was = journal.journal_date
                _financial_year(db, company.id, on, audit, [])
                posting.reverse(db, journal, was, f"Re-dated to {on:%d-%b-%Y}, the date on the previous ERP's ledger",
                                audit, allow_document=True)
                net, value, tax = (money(order.net_receivable), money(order.excluding_tax_value),
                                   money(order.sales_tax_value))
                amounts = {"receivable": net, "revenue": value}
                if tax:
                    amounts["output_tax"] = tax
                fresh = posting.post(db, PostingRequest(
                    event_code="SALES_INVOICE_POSTED", company_id=company.id, journal_date=on,
                    branch_id=order.branch_id, description=f"Invoice {order.doc_number} — {customer.name}",
                    reference=order.customer_po_number, document_type="SALES_ORDER", document_id=order.id,
                    source_module="sales", source_reference=order.doc_number,
                    amounts=amounts, customer_id=order.customer_id), audit)
                # The receivable item is left as it is: the database allows one per
                # document and lets it change only by cancellation. It keeps the
                # sales order's date, so aging still counts from that date.
                order.journal_entry_id = fresh.id
                db.flush()
                moved += 1
                print(f"  {customer.name[:28]:<28} {number}: {was:%d-%b-%Y} -> {on:%d-%b-%Y}  {net:>14,.2f}  {fresh.journal_number}")
        print(f"Moved {moved} invoices; {same} were already on the old ledger's date.")
        if apply:
            db.commit()
            print("Committed.")
        else:
            db.rollback()
            print("Dry run: nothing was changed.")
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    run(apply="--apply" in sys.argv)
